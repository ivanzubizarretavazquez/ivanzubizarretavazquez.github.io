function applyLanguage(lang) {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const value = translations[lang][key];
    if (value !== undefined) {
      el.textContent = value;
    }
  });

  document.documentElement.setAttribute("lang", lang);

  document.querySelectorAll("[data-lang-label]").forEach((el) => {
    el.classList.toggle("is-active", el.getAttribute("data-lang-label") === lang);
  });

  localStorage.setItem("iz-portfolio-lang", lang);
}

function setupScanBar() {
  const bar = document.getElementById("scanBar");
  let ticking = false;

  function update() {
    const scrollTop = window.scrollY;
    const docHeight = document.documentElement.scrollHeight - window.innerHeight;
    const pct = docHeight > 0 ? (scrollTop / docHeight) * 100 : 0;
    bar.style.width = pct + "%";

    // Fase 2 — CameraController: el mismo progreso que llena la barra
    // pilota el recorrido de la cámara por el universo 3D.
    if (window.NetworkBackground && window.NetworkBackground.isActive()) {
      window.NetworkBackground.setScrollProgress(pct / 100);
    }

    ticking = false;
  }

  window.addEventListener("scroll", () => {
    if (!ticking) {
      requestAnimationFrame(update);
      ticking = true;
    }
  });

  update();
}

function setupReveals() {
  const targets = document.querySelectorAll(".reveal, .reveal-group");
  if (!("IntersectionObserver" in window) || targets.length === 0) {
    targets.forEach((el) => el.classList.add("is-visible"));
    return;
  }

  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          observer.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.15 }
  );

  targets.forEach((el) => observer.observe(el));
}

document.addEventListener("DOMContentLoaded", () => {
  const stored = localStorage.getItem("iz-portfolio-lang");
  const initialLang = stored === "en" ? "en" : "es";
  applyLanguage(initialLang);

  const toggle = document.getElementById("langToggle");
  toggle.addEventListener("click", () => {
    const current = document.documentElement.getAttribute("lang") === "en" ? "en" : "es";
    applyLanguage(current === "es" ? "en" : "es");
  });

  setupScanBar();
  setupReveals();
  setupNetworkBackground();
});

function setupNetworkBackground() {
  // Fase 1: universo 3D ambiental. Si Three.js no cargó (bloqueado, sin
  // red, navegador sin WebGL) la web sigue funcionando exactamente igual
  // que antes: el canvas queda vacío y transparente.
  const canvas = document.getElementById("networkCanvas");
  if (!canvas) return;

  if (typeof THREE === "undefined" || !window.NetworkBackground) {
    canvas.style.display = "none";
    return;
  }

  try {
    const supportsWebGL = (() => {
      try {
        const testCanvas = document.createElement("canvas");
        return Boolean(
          window.WebGLRenderingContext &&
            (testCanvas.getContext("webgl") ||
              testCanvas.getContext("experimental-webgl"))
        );
      } catch (e) {
        return false;
      }
    })();

    if (!supportsWebGL) {
      canvas.style.display = "none";
      return;
    }

    window.NetworkBackground.init(canvas);
  } catch (err) {
    // Cualquier fallo del universo 3D nunca debe romper el portfolio.
    canvas.style.display = "none";
    console.warn("NetworkBackground no se pudo inicializar:", err);
  }
}
